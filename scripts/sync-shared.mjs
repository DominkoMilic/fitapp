#!/usr/bin/env node
/**
 * Copies pure app modules into supabase/functions/_shared so Edge Functions (Deno) run the exact
 * code the app tests. Rewrites '@/...' and extensionless relative imports to Deno-style paths.
 *
 *   node scripts/sync-shared.mjs          # write
 *   node scripts/sync-shared.mjs --check  # exit 1 when out of date (part of `npm run check`)
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const FILES = {
  'src/domain/account/delete-account.ts': 'delete-account.ts',
};
const RENAMES = {
  zod: 'npm:zod@4',
};

let stale = false;
for (const [src, dest] of Object.entries(FILES)) {
  let code = readFileSync(join(root, src), 'utf8');
  for (const [from, to] of Object.entries(RENAMES))
    code = code.split(`from '${from}'`).join(`from '${to}'`);
  if (/from '@\//.test(code)) throw new Error(`${src} has an unmapped '@/' import`);
  const out = `// GENERATED by scripts/sync-shared.mjs from ${src}. Do not edit.\n${code}`;
  const path = join(root, 'supabase/functions/_shared', dest);
  if (process.argv.includes('--check')) {
    let cur = '';
    try {
      cur = readFileSync(path, 'utf8');
    } catch {}
    if (cur !== out) {
      console.error(`${path} is out of date. Run: node scripts/sync-shared.mjs`);
      stale = true;
    }
  } else writeFileSync(path, out);
}
if (stale) process.exit(1);
console.log(
  process.argv.includes('--check')
    ? 'Edge Function shared code is up to date.'
    : 'Synced Edge Function shared code.',
);
