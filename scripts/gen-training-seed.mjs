#!/usr/bin/env node
/**
 * Generates the system exercise/template seed migration from src/domain/training/catalogue.ts,
 * so the app's bundled catalogue and the database never drift apart.
 *
 *   node scripts/gen-training-seed.mjs          # write the migration
 *   node scripts/gen-training-seed.mjs --check  # exit 1 if the migration is out of date
 *
 * Requires Node 22.6+ (runs the TypeScript catalogue directly).
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const { EXERCISES, TEMPLATES } = await import(join(root, 'src/domain/training/catalogue.ts'));
const { exerciseId, stableUuid } = await import(join(root, 'src/domain/training/stable-id.ts'));
const OUT = join(root, 'supabase/migrations/20261110000200_training_seed.sql');

const q = (v) => (v === null || v === undefined ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const arr = (a) => (a.length ? `array[${a.map(q).join(', ')}]::text[]` : `'{}'::text[]`);
const num = (v) => (v === null || v === undefined ? 'null' : String(v));

let sql = `-- GENERATED by scripts/gen-training-seed.mjs from src/domain/training/catalogue.ts. Do not edit.
-- Idempotent: re-running updates system rows in place.

`;
sql += `insert into public.exercises (id, owner_id, slug, name, category, muscle_groups, equipment, difficulty,
  tracking_type, is_unilateral, instructions, caution_notes, contraindication_tags, default_sets, default_reps_min,
  default_reps_max, default_duration_s, met) values\n`;
sql += EXERCISES.map(
  (e) =>
    `  (${q(exerciseId(e.slug))}, null, ${q(e.slug)}, ${q(e.name)}, ${q(e.category)}, ${arr(e.muscleGroups)}, ${arr(e.equipment)}, ${q(e.difficulty)}, ${q(e.tracking)}, ${e.unilateral}, ${arr(e.instructions)}, ${q(e.caution)}, ${arr(e.contraindications)}, ${num(e.defaultSets)}, ${num(e.repsMin)}, ${num(e.repsMax)}, ${num(e.durationS)}, ${num(e.met)})`,
).join(',\n');
sql += `
on conflict (id) do update set
  slug = excluded.slug, name = excluded.name, category = excluded.category, muscle_groups = excluded.muscle_groups,
  equipment = excluded.equipment, difficulty = excluded.difficulty, tracking_type = excluded.tracking_type,
  is_unilateral = excluded.is_unilateral, instructions = excluded.instructions, caution_notes = excluded.caution_notes,
  contraindication_tags = excluded.contraindication_tags, default_sets = excluded.default_sets,
  default_reps_min = excluded.default_reps_min, default_reps_max = excluded.default_reps_max,
  default_duration_s = excluded.default_duration_s, met = excluded.met;

`;
sql += `insert into public.workout_templates (id, slug, name, category, intensity, estimated_minutes, short_version_slug, description) values\n`;
sql += TEMPLATES.map(
  (t) =>
    `  (${q(stableUuid(`pace:template:${t.slug}`))}, ${q(t.slug)}, ${q(t.name)}, ${q(t.category)}, ${q(t.intensity)}, ${t.minutes}, ${q(t.shortVersion)}, ${q(t.description)})`,
).join(',\n');
sql += `
on conflict (id) do update set
  slug = excluded.slug, name = excluded.name, category = excluded.category, intensity = excluded.intensity,
  estimated_minutes = excluded.estimated_minutes, short_version_slug = excluded.short_version_slug,
  description = excluded.description;

delete from public.workout_template_exercises
where template_id in (${TEMPLATES.map((t) => q(stableUuid(`pace:template:${t.slug}`))).join(', ')});

`;
const rows = TEMPLATES.flatMap((t) =>
  t.exercises.map(
    (x, i) =>
      `  (${q(stableUuid(`pace:template:${t.slug}:${i}`))}, ${q(stableUuid(`pace:template:${t.slug}`))}, ${q(exerciseId(x.slug))}, ${q(x.phase)}, ${i}, ${x.sets}, ${num(x.repsMin)}, ${num(x.repsMax)}, ${num(x.durationS)}, ${x.restS}, ${x.alternative ? q(exerciseId(x.alternative)) : 'null'})`,
  ),
);
sql += `insert into public.workout_template_exercises (id, template_id, exercise_id, phase, order_index, sets, reps_min,
  reps_max, duration_s, rest_s, alternative_exercise_id) values\n${rows.join(',\n')};\n`;

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(OUT, 'utf8');
  } catch {}
  if (current !== sql) {
    console.error('Training seed migration is out of date. Run: node scripts/gen-training-seed.mjs');
    process.exit(1);
  }
  console.log('Training seed migration is up to date.');
} else {
  writeFileSync(OUT, sql);
  console.log(`Wrote ${OUT} (${EXERCISES.length} exercises, ${TEMPLATES.length} templates, ${rows.length} template rows)`);
}
