#!/usr/bin/env node
/**
 * Generates the reference food seed migration from USDA FoodData Central "SR Legacy"
 * (public domain, CC0): https://fdc.nal.usda.gov/download-datasets
 *
 *   curl -o sr.zip https://fdc.nal.usda.gov/fdc-datasets/FoodData_Central_sr_legacy_food_csv_2018-04.zip
 *   unzip sr.zip -d /some/empty/dir
 *   node scripts/gen-usda-seed.mjs /some/empty/dir/FoodData_Central_sr_legacy_food_csv_2018-04
 *
 * Output: supabase/migrations/20261111000200_usda_foods_seed.sql (idempotent upserts).
 * Values are per 100 g. Foods without an energy value are skipped; missing macros stay null
 * (shown as "partial data" in the app, never as zero).
 */
import { createReadStream, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { createInterface } from 'node:readline';
import { fileURLToPath } from 'node:url';

const dir = process.argv[2];
if (!dir) {
  console.error('Usage: node scripts/gen-usda-seed.mjs <path to unzipped SR Legacy CSV folder>');
  process.exit(1);
}
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(root, 'supabase/migrations/20261111000200_usda_foods_seed.sql');

/** Categories left out: baby foods, fast foods, Native foods, restaurant, branded, QC materials. */
const EXCLUDED_CATEGORIES = new Set(['3', '21', '24', '25', '26', '27']);
const NUTRIENTS = {
  1008: 'kcal',
  1003: 'protein_g',
  1005: 'carbs_g',
  1004: 'fat_g',
  1079: 'fibre_g',
};
const MAX_PORTIONS = 5;

function parseCsvLine(line) {
  const out = [];
  let cur = '';
  let quoted = false;
  for (let i = 0; i < line.length; i++) {
    const c = line[i];
    if (quoted) {
      if (c === '"' && line[i + 1] === '"') {
        cur += '"';
        i++;
      } else if (c === '"') quoted = false;
      else cur += c;
    } else if (c === '"') quoted = true;
    else if (c === ',') {
      out.push(cur);
      cur = '';
    } else cur += c;
  }
  out.push(cur);
  return out;
}

async function* rows(file) {
  const rl = createInterface({ input: createReadStream(join(dir, file)), crlfDelay: Infinity });
  let header = null;
  for await (const line of rl) {
    if (!line) continue;
    const cells = parseCsvLine(line);
    if (!header) header = cells;
    else yield Object.fromEntries(header.map((h, i) => [h, cells[i] ?? '']));
  }
}

const categories = new Map();
for await (const r of rows('food_category.csv')) categories.set(r.id, r.description);
const units = new Map();
for await (const r of rows('measure_unit.csv')) units.set(r.id, r.name);

const foods = new Map();
for await (const r of rows('food.csv')) {
  if (EXCLUDED_CATEGORIES.has(r.food_category_id)) continue;
  foods.set(r.fdc_id, {
    id: r.fdc_id,
    name: r.description.trim(),
    category: categories.get(r.food_category_id) ?? null,
    portions: [],
  });
}
for await (const r of rows('food_nutrient.csv')) {
  const key = NUTRIENTS[r.nutrient_id];
  const f = key && foods.get(r.fdc_id);
  if (!f) continue;
  const v = Number(r.amount);
  if (Number.isFinite(v) && v >= 0) f[key] = Math.round(v * 100) / 100;
}
for await (const r of rows('food_portion.csv')) {
  const f = foods.get(r.fdc_id);
  const grams = Number(r.gram_weight);
  if (!f || !(grams > 0) || f.portions.length >= MAX_PORTIONS) continue;
  const amount = Number(r.amount) || 1;
  const unit = r.measure_unit_id !== '9999' ? units.get(r.measure_unit_id) : '';
  const label = [amount, unit, r.portion_description || r.modifier]
    .filter(Boolean)
    .join(' ')
    .replace(/\s+/g, ' ')
    .trim();
  if (label && label.length <= 80) f.portions.push({ label, grams: Math.round(grams * 10) / 10 });
}

const kept = [...foods.values()].filter(
  (f) => f.kcal !== undefined && f.kcal <= 950 && f.name.length <= 200,
);
const q = (v) => (v === null || v === undefined ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const n = (v) =>
  v === undefined || v === null ? 'null' : String(Math.min(v, v > 100 ? 950 : 100));

let sql = `-- GENERATED by scripts/gen-usda-seed.mjs from USDA FoodData Central SR Legacy (CC0). Do not edit.
-- ${kept.length} foods, nutrition per 100 g. Idempotent.
`;
const BATCH = 500;
for (let i = 0; i < kept.length; i += BATCH) {
  sql += `
insert into public.foods (owner_id, name, category, basis, kcal, protein_g, carbs_g, fat_g, fibre_g, portions, source, external_id, nutritional_confidence) values
${kept
  .slice(i, i + BATCH)
  .map(
    (f) =>
      `  (null, ${q(f.name)}, ${q(f.category)}, 'per_100g', ${n(f.kcal)}, ${n(f.protein_g)}, ${n(f.carbs_g)}, ${n(f.fat_g)}, ${n(f.fibre_g)}, ${q(JSON.stringify(f.portions))}::jsonb, 'usda', ${q(f.id)}, 'reference')`,
  )
  .join(',\n')}
on conflict (source, external_id) do update set
  name = excluded.name, category = excluded.category, kcal = excluded.kcal, protein_g = excluded.protein_g,
  carbs_g = excluded.carbs_g, fat_g = excluded.fat_g, fibre_g = excluded.fibre_g, portions = excluded.portions;
`;
}
writeFileSync(OUT, sql);
const sizeKb = Math.round(Buffer.byteLength(sql) / 1024);
console.log(
  `Wrote ${OUT}: ${kept.length} foods (of ${foods.size} in kept categories), ${sizeKb} KB`,
);
