export type TemplatePhase = 'warmup' | 'main' | 'cooldown';

export interface TemplateExercise {
  slug: string;
  phase: TemplatePhase;
  sets: number;
  repsMin: number | null;
  repsMax: number | null;
  durationS: number | null;
  restS: number;
  /** Used when the exercise is contraindicated or needs equipment the user lacks. */
  alternative: string | null;
}

export interface CatalogueTemplate {
  slug: string;
  name: string;
  category: 'strength' | 'conditioning' | 'recovery' | 'mobility' | 'football' | 'sport_skills';
  intensity: 'easy' | 'moderate' | 'hard';
  minutes: number;
  shortVersion: string | null;
  description: string;
  exercises: TemplateExercise[];
}

